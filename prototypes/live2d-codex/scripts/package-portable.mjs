import { cp, mkdir, writeFile, readFile, stat, readdir, access } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { createReadStream } from 'node:fs';
import { resolve, join, relative } from 'node:path';
import { pathToFileURL } from 'node:url';
import { execFileSync } from 'node:child_process';
import { writeManifest } from '../../../tools/release/manifest.mjs';
const root = resolve(import.meta.dirname,'..'), workspace = resolve(root,'../..');
const { version } = JSON.parse(await readFile(join(root,'package.json'),'utf8'));
const option = key => process.argv.find(value => value.startsWith(`--${key}=`))?.slice(key.length+3);
if (process.argv.includes('--update-app')) throw new Error('In-place merging is disabled. Build a fresh package and use the installer to upgrade.');
const output = resolve(option('out') || join(workspace,`release/VibeVoice-${version}-win-x64`));
try { await access(output); throw new Error(`Output already exists; use a new staging path: ${output}`); } catch (error) { if(error.code !== 'ENOENT') throw error; }
const resources = resolve(process.env.VIBE_RESOURCE_APP || root);
await mkdir(output,{recursive:true});
const appDir = join(output,'resources/app'); await mkdir(appDir,{recursive:true});
const clean = source => !/(^|[/\\])(__pycache__|cache|\.cache|\.git)([/\\]|$)/.test(relative(resources,source)) && !/\.(pyc|pyo|log|tmp)$/.test(source);
await cp(join(root,'node_modules/electron/dist'),output,{recursive:true,filter:src=>!src.endsWith('electron.exe')});
await cp(join(root,'node_modules/electron/dist/electron.exe'),join(output,'VibeVoice.exe'));
for (const file of ['main.cjs','preload.cjs','voice-resources.json']) await cp(join(root,file),join(appDir,file));
for (const dir of ['backend','renderer','dist']) await cp(join(root,dir),join(appDir,dir),{recursive:true,filter:src=>!src.includes('__pycache__') && !src.endsWith('dots.mjs')});
for (const dir of ['vendor']) await cp(join(resources,dir),join(appDir,dir),{recursive:true,filter:clean});
await mkdir(join(appDir,'runtime'),{recursive:true});
await cp(join(resources,'runtime/node.exe'),join(appDir,'runtime/node.exe'));
for (const name of ['rainy-window-v2-4k']) await cp(join(resources,'assets',name),join(appDir,'assets',name),{recursive:true});
for (const name of ['rainy-window-male','character-previews']) await cp(join(root,'assets',name),join(appDir,'assets',name),{recursive:true});
await mkdir(join(appDir,'scripts'),{recursive:true});
await cp(join(root,'scripts/wallpaper-host.ps1'),join(appDir,'scripts/wallpaper-host.ps1'));
for (const name of ['sherpa-onnx-node','sherpa-onnx-win-x64']) await cp(join(root,'node_modules',name),join(appDir,'node_modules',name),{recursive:true});
await writeFile(join(appDir,'package.json'),JSON.stringify({name:'vibe-voice',version,type:'module',main:'main.cjs',private:true},null,2));
await writeFile(join(appDir,'portable.json'),JSON.stringify({version,platform:'win32-x64',backend:'codex'}));
await cp(join(root,'PORTABLE-README.md'),join(output,'USER-GUIDE.md'));
await cp(join(root,'THIRD-PARTY-NOTICES.md'),join(output,'THIRD-PARTY-NOTICES.md'));
await cp(join(workspace,'LICENSE'),join(output,'LICENSE-VibeVoice.txt'));
await cp(join(root,'licenses'),join(output,'licenses'),{recursive:true});
execFileSync(join(appDir,'runtime/node.exe'),['--input-type=module','-e',`await import(${JSON.stringify(pathToFileURL(join(appDir,'backend/codex.mjs')).href)});await import(${JSON.stringify(pathToFileURL(join(appDir,'backend/resident-speech.mjs')).href)});`],{windowsHide:true,stdio:'pipe'});
console.log(JSON.stringify({output,...await writeManifest(output,version)}));
